"""Render the Markdown report and PR body. All text is built by the control plane from
real data (actual diff, actual test results); model output is never trusted to describe the change."""
from __future__ import annotations

from typing import Any


def _tbl(headers: list[str], rows: list[list[Any]]) -> str:
    if not rows:
        return "_None._\n"
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(c).replace("|", "\\|").replace("\n", " ") for c in r) + " |")
    return "\n".join(out) + "\n"


def render_pr_body(cs: dict, state: dict) -> str:
    base = state.get("baseline") or {}
    after = cs.get("after_summary") or {}
    gates = cs.get("gates", [])
    rows_ev = [
        ["Tests passed", base.get("passed", "n/a"), after.get("passed", "n/a")],
        ["Tests failed", base.get("failed", "n/a"), after.get("failed", "n/a")],
        ["Flaky tests excluded", len(base.get("flaky", [])), len(base.get("flaky", []))],
        ["Coverage", "not measured (MVP)", "not measured (MVP)"],
    ]
    files = "\n".join(f"- `{f}`" for f in cs.get("files", []))
    addressed = "\n".join(f"- `{f['id']}` {f['symbol']} ({f['file']}:{f['line']}) — {f['confidence']} confidence" for f in cs["findings"])
    not_touched = [f for f in state["findings"]["dead_code"] if f["confidence"] != "high"]
    nt = "\n".join(f"- `{f['id']}` {f['symbol']} — {f['confidence']}: {f['evidence'][-1]}" for f in not_touched[:15]) or "_Nothing else flagged._"
    return f"""## Summary
Automated maintenance change: remove {len(cs['findings'])} high-confidence unused symbol(s). Generated by the Code Maintenance Agent. **A human must review and merge.**

## Change type
- [x] Dead code removal
- [ ] Duplicate extraction
- [ ] Unused dependency removal

## Evidence
{_tbl(['Check', 'Baseline', 'After change'], rows_ev)}
### Verification gates
{_tbl(['Gate', 'Result', 'Detail'], [[g['name'], 'PASS' if g['passed'] else 'FAIL', g['detail']] for g in gates])}
## Files changed (from the actual diff)
{files}

Diff size: +{cs.get('added', 0)} / -{cs.get('removed', 0)} lines. Protected paths touched: none (policy-enforced).

## Findings addressed
{addressed}

## Not touched (needs a human decision)
{nt}

## Reviewer checklist
- Removed code may leave **unused imports**: run your formatter / organise-imports step.
- Confirm no consumer **outside this repository** calls the removed symbols (the agent can only see this repo).

## How to reproduce
Run `{state['repo']}` at commit `{state['commit']}` (run id `{state['run_id']}`), then apply the attached patch and run the test command from `.agent.yml`.

## Rollback
`git revert <merge-commit>`. No data or schema changes.

## Authorisation
Access to this repository was authorised by **{(state.get('consent') or {}).get('granted_by', 'unknown')}** on {(state.get('consent') or {}).get('granted_at', 'unknown')} \
(permissions: {', '.join((state.get('consent') or {}).get('scopes', []))}; method: {(state.get('consent') or {}).get('method', 'n/a')}).

---
_Generated by Code Maintenance Agent. Do not merge unless your normal CI is green._
"""


def render_report(state: dict) -> str:
    f = state["findings"]
    scan = state["scan"]
    base = state.get("baseline")
    L: list[str] = []
    L.append(f"# Code maintenance report\n")
    L.append(f"- **Repo:** `{state['repo']}`\n- **Commit:** `{state['commit']}`\n- **Run:** `{state['run_id']}`  \n"
             f"- **Status:** {state['status']}\n- **Mode:** report + PR, human merges\n"
             f"- **Sandbox:** {state.get('sandbox', {}).get('sandbox', 'not used')}"
             f" (network isolated: {state.get('sandbox', {}).get('network_isolated', 'n/a')}, "
             f"strong isolation: {state.get('sandbox', {}).get('strong_isolation', 'n/a')})\n")
    c = state.get("consent")
    L.append("## Authorisation\n")
    if c:
        L.append(_tbl(["Field", "Value"], [
            ["Repository", c["repo_display"] + f" ({c['repo']})"], ["Granted by", c["granted_by"]], ["Method", c["method"]],
            ["Permissions", ", ".join(c["scopes"])], ["Granted at", c["granted_at"]], ["Expires", c["expires_at"]],
            ["Trust", f"{c['trust']} ({c['trust_reason']})"], ["Repository visibility", c.get("repo_info", {}).get("visibility", "unknown")],
            ["Notice sha256", c["notice_sha256"][:16] + "..."], ["CI run", c.get("ci_run") or "n/a"]]))
    else:
        L.append("_No consent was recorded, so **no access to the repository took place**._\n")
    if state.get("notes"):
        L.append("## Notes\n" + "\n".join(f"- {n}" for n in state["notes"]) + "\n")

    L.append("## Executive summary\n")
    n_high = sum(1 for x in f["dead_code"] if x["confidence"] == "high")
    L.append(f"- Dead code: **{len(f['dead_code'])}** findings ({n_high} high confidence)\n"
             f"- Duplicate blocks: **{len(f['duplicates'])}**\n"
             f"- Secrets found: **{len(scan['secrets'])}**; sensitive files present: **{len(scan['sensitive_files'])}**\n"
             f"- Prompt-injection-like text found in repo: **{len(scan['injections'])}**\n"
             f"- Change sets: **{len(state['change_sets'])}** "
             f"({sum(1 for c in state['change_sets'] if c['decision'] == 'ready')} ready for human review)\n")

    L.append("## Security findings\n")
    L.append("### Possible secrets (values redacted; files with these were excluded from LLM context)\n")
    L.append(_tbl(["Kind", "Location", "Preview"], [[s["kind"], f"{s['file']}:{s['line']}", s["preview"]] for s in scan["secrets"]]))
    L.append("### Sensitive files present (never opened by the agent)\n")
    L.append("\n".join(f"- `{p}`" for p in scan["sensitive_files"]) + "\n" if scan["sensitive_files"] else "_None._\n")
    L.append("### Instruction-like text aimed at AI agents (treated as DATA, not obeyed)\n")
    L.append(_tbl(["Kind", "Location", "Excerpt (quoted data)"], [[i["kind"], f"{i['file']}:{i['line']}", f"`{i['excerpt']}`"] for i in scan["injections"]]))

    L.append("## Test baseline\n")
    if base:
        L.append(_tbl(["Runs", "Passed", "Failed", "Skipped", "Flaky", "Green", "Avg duration"],
                      [[base["runs"], base["passed"], base["failed"], base["skipped"], len(base["flaky"]), base["green"], f"{base['avg_duration']:.1f}s"]]))
        if not base["green"]:
            L.append(f"**Baseline not usable:** {base['reason']}. No changes were attempted.\n")
            if base.get("output_tail"):
                L.append(f"Last output (exit code {base.get('exit_code')}, secrets redacted):\n\n```text\n{base['output_tail']}\n```\n")
    else:
        L.append("_Tests were not run in this mode._\n")

    L.append("## Duplicate code (report only)\n")
    L.append(_tbl(["ID", "Confidence", "Location A", "Location B", "Evidence"],
                  [[d["id"], d["confidence"], f"{d['file']}:{d['line']}-{d['end_line']}",
                    f"{d['related'][0]['file']}:{d['related'][0]['start']}-{d['related'][0]['end']}", d["evidence"][0]] for d in f["duplicates"]]))

    L.append("## Dead code\n")
    L.append(_tbl(["ID", "Confidence", "Symbol", "Location", "Action", "Status", "Evidence"],
                  [[d["id"], d["confidence"], f"`{d['symbol']}`", f"{d['file']}:{d['line']}", d["proposed_action"], d["status"], "; ".join(d["evidence"])] for d in f["dead_code"]]))
    L.append(f"_Languages analysed: {', '.join(state.get('languages') or []) or 'none'} (build tool: {state.get('build_tool') or 'n/a'}). "
             "Only private symbols can be auto-removed; public API, reflection/annotation-wired code and side-effecting initialisers are report-only._\n")

    L.append("## Change sets\n")
    if not state["change_sets"]:
        L.append("_No change sets were produced._\n")
    for cs in state["change_sets"]:
        L.append(f"### {cs['id']}: {cs['type']} — **{cs['decision'].upper()}**\n")
        L.append(f"- Symbols: {', '.join('`' + x['symbol'] + '`' for x in cs['findings']) or 'none'}\n"
                 f"- Files: {', '.join('`' + x + '`' for x in cs.get('files', [])) or 'none'}  (+{cs.get('added', 0)}/-{cs.get('removed', 0)})\n"
                 f"- Policy: {'ALLOW' if cs['policy']['allowed'] else 'DENY: ' + '; '.join(cs['policy']['reasons'])}\n")
        L.append(_tbl(["Gate", "Result", "Detail"], [[g["name"], "PASS" if g["passed"] else "FAIL", g["detail"]] for g in cs.get("gates", [])]))
        if cs.get("skipped"):
            L.append("Skipped: " + "; ".join(f"`{s['symbol']}` ({s['reason']})" for s in cs["skipped"]) + "\n")
        if cs.get("branch"):
            L.append(f"- Branch: `{cs['branch']['branch']}` @ `{cs['branch']['commit'][:10]}` (pushed: {cs['branch']['pushed']})\n")
        if cs.get("pr"):
            L.append(f"- PR: {cs['pr'].get('url') or 'dry-run: ' + cs['pr'].get('reason', '')}\n")
        if cs.get("patch_file"):
            L.append(f"- Patch file: `{cs['patch_file']}`\n")

    llm = state.get("llm", {})
    L.append("## Agent actions\n")
    L.append(f"- LLM triage: {'enabled' if llm.get('enabled') else 'disabled'}; calls: {llm.get('calls', 0)}; downgraded: {llm.get('downgraded', 0)}\n"
             f"- Files scanned: {scan['files_scanned']}; files that failed to parse: {len(state.get('parse_failures', []))}\n"
             f"- Audit log: `{state.get('audit_log')}` (hash chain verified: {state.get('audit_verified')})\n")
    return "\n".join(L)
